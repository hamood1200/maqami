export const MAQAM_BY_ID: Record<string, Maqam> = Object.fromEntries(MAQAMAT.map((m) => [m.id, m]))

export function familyName(id: FamilyId): string {
  return FAMILIES.find((f) => f.id === id)?.name ?? ''
}

/** النغمة المستخدمة لدرجة معيّنة في الهبوط */
export function descendingNote(m: Maqam, degree: number): string {
  if (!m.descending) return m.notes[degree]
  return m.descending[m.notes.length - 1 - degree]
}
