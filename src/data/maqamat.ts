import type { JinsId } from './ajnas'

export type FamilyId =
  | 'rast'
  | 'bayati'
  | 'sikah'
  | 'hijaz'
  | 'saba'
  | 'nahawand'
  | 'ajam'
  | 'kurd'
  | 'nikriz'

export interface JinsPlacement {
  jins: JinsId
  /** رقم الدرجة التي يبدأ عندها الجنس (0 = القرار) */
  at: number
  /** عدد النغمات التي يغطيها داخل الديوان */
  length: number
  /** اسم بديل للجنس في هذا المقام إن وُجد */
  label?: string
}

export interface Clip {
  videoId: string
  song: string
  artist: string
  /** بداية ونهاية المقطع بالثواني */
  start: number
  end: number
  /** ماذا تسمع في هذا المقطع */
  hint: string
  /** التوقيت تقديري ويحتاج مراجعة بالأذن */
  needsReview?: boolean
}

export interface Maqam {
  id: string
  name: string
  family: FamilyId
  /** النغمات صعوداً من القرار إلى الجواب */
  notes: string[]
  /** النغمات هبوطاً (إن اختلفت عن الصعود) من الجواب إلى القرار */
  descending?: string[]
  ajnas: JinsPlacement[]
  /** درجة الغمّاز (النغمة المهيمنة) */
  ghammaz: number
  /** هل هو من المقامات الأساسية الثمانية */
  basic: boolean
  description: string
  tips?: string[]
  examples: Clip[]
}

